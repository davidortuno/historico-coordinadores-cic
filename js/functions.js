        // Modal de Semblanza
        function cicHcOpenModal(id) {
            const person = cicHcData.find(item => item.id === Number(id));
            if (!person) return;

            cicHcModalInitialsEl.textContent = person.initials;
            cicHcModalPeriodEl.textContent = `Periodo: ${person.period}`;
            cicHcModalNameEl.textContent = person.name;

            const paragraphs = Array.isArray(person.biography) ? person.biography : [person.biography];
            cicHcModalBioEl.innerHTML = paragraphs
                .map(p => `<p class="cic-hc-modal-text">${p}</p>`)
                .join('');

            cicHcModalEl.classList.add('cic-hc-open');
            document.body.style.overflow = 'hidden';
            cicHcModalCloseTopEl.focus();
        }

        function cicHcCloseModal() {
            cicHcModalEl.classList.remove('cic-hc-open');
            document.body.style.overflow = '';
        }

        function cicHcResetAll() {
            cicHcSearchTerm = '';
            cicHcSelectedEra = 'all';
            cicHcSearchInputEl.value = '';
            cicHcEraSelectEl.value = 'all';
            cicHcRender();
        }

